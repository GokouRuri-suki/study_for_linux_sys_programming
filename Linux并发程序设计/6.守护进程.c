/**

● 守护进程(Daemon)是Linux三种进程类型之一
● 通常在系统启动时运行，系统关闭时结束
● Linux系统中大量使用，很多服务程序以守护进程形式运行。


● 始终在后台运行
●独立于任何终端（交互进程和终端关联，守护进程无法使用!!!---stdin,stdout,stderr!!!!）
● 周期性的执行某种任务或等待处理特定事件


● Linux以会话(session)、进程组的方式管理进程
●每个进程属于一个进程组（一个程序对应一个进程组，父进程和子进程在同一个进程组里）
●会话是一个或多个进程组的集合。通常用户打开一个终端时，系统会创建一个会话(shell命令的窗口)。所有通过该终端运行的进程都属于这个会话。一个会话最多只能有一个控制终端。
● 终端关闭时，所有相关进程都会被结束。守护进程脱离终端了，所以不会被结束。



特性        	调用前              	调用 setsid() 后
会话 ID     	继承自父进程        	等于当前进程 PID
进程组 ID   	可能等于父进程组 ID 	等于当前进程 PID
控制终端    	可能有              	无
进程角色    	普通进程            	会话首进程 + 进程组组长


- *会话 (Session)*：最高层。一个会话通常对应一个登录用户或一个终端窗口。
- *进程组 (Process Group)*：中间层。一个会话可以包含多个进程组。
- *进程 (Process)*：最底层。一个进程组包含多个进程。



会话 (SID: 100)
├── 进程组 (PGID: 100) [前台组]
│   ├── 进程 A (PID: 100) <--- 会话首进程 & 进程组组长
│   └── 进程 B (PID: 101)
└── 进程组 (PGID: 200) [后台组]
    ├── 进程 C (PID: 200) <--- 进程组组长
    └── 进程 D (PID: 201)
 */
#include <stdio.h>
#include <stdlib.h>
#include <sys/stat.h>
#include <sys/types.h>
#include <unistd.h>

void baseOprAboutDaemon();

int main() {
  baseOprAboutDaemon();
  return 0;
}

void baseOprAboutDaemon() {
  pid_t pid;
  pid_t sPid;

  // 第一步：第一次 Fork
  // 目的：让父进程退出。这样做的核心原因是：
  // 1. 确保子进程不再是“进程组组长”（这是调用 setsid 的前提条件）。
  // 2. 子进程会被 init/systemd (PID 1) 收养，脱离原终端的控制。
  if ((pid = fork()) < 0) {
    perror("创建失败");
    exit(-1);
  } else if (pid > 0) {
    // 父进程直接退出，将控制权交还给终端
    exit(EXIT_SUCCESS);
  }

  // 第二步：创建新会话 (Setsid)
  // 此时子进程肯定不是进程组组长，调用会成功。
  // 作用：
  // 1. 创建一个全新的会话，当前进程成为“会话首进程”。
  // 2. 创建一个全新的进程组，当前进程成为“进程组组长”。
  // 3. 彻底切断与控制终端的联系（脱离终端）。
  if ((sPid = setsid()) < 0) {
    perror("setsid error");
    return;
  }

  // 注意：这里不需要判断 sPid > 0 就退出。
  // sPid 返回的是新会话的 ID（通常等于当前
  // PID），表示我们已经是会话老大了，应该继续执行后续逻辑。

  // 更改工作目录至根目录 "/"
  chdir("/");
  // 目的：防止因启动守护进程的原始目录（如 U
  // 盘或网络挂载点）被卸载而导致进程异常。

  //  屏蔽码(umask)，是权限码的一个对应意思，权限码0666代表这--rw--rw--rw--
  //  屏蔽码则是权限最大减去屏蔽值022 --rw--r--r--
  if (umask(0) < 0) {
    perror("umask error");
    exit(-1);
  }
  /*
  默认权限      	0666  	110 110 110 	所有人可读写
  屏蔽码        	022   	000 010 010 	屏蔽掉“组”和“其他”的写权限
  取反 (~)      	~022  	111 101 101 	保留所有读/执行，只去掉特定的写
  位与 (&)      	0644  	110 100 100 	最终结果：rw-r--r--
  */

  for (int i = 0; i < getdtablesize(); i++) {
    close(i);
  }
  while (1)
    ;
}
